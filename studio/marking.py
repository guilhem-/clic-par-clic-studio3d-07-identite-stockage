"""Marking of the studio's renders (module 4): always invisible, optionally visible.

Called by the worker (worker.py) right after Blender, before storing the files: the scene code, written
by the model, can neither avoid nor change it.
  - invisible, always: XMP packet (IPTC source type "created by generative AI", date, generator, request
    id) and text fields in the PNG; `asset` field of the GLB;
  - visible, optionally: an always identical banner, bottom right (source and date).
Module 5: the trace of the library assets used (name, source, license) joins the marking.
"""
import json
import struct
import time
import uuid
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont
from PIL.PngImagePlugin import PngInfo

GENERATOR = "AI studio3D"
# IPTC "Digital Source Type" vocabulary: created by a trained model (generative AI).
SOURCE_TYPE = "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia"
# Font from the Debian fonts-dejavu-core package: same rendering everywhere.
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"


def info(request: dict, end: float, assets: list | None = None, library=None) -> dict:
    """What the mark carries: request id, end date of the render (UTC), assets used."""
    t = time.gmtime(end)
    ident = request.get("id") or str(uuid.uuid4())
    return {"id": ident, "number": request.get("number", ""),
            "date": time.strftime("%Y-%m-%dT%H:%M:%SZ", t),
            "day": time.strftime("%Y-%m-%d", t),
            "rfc1123": time.strftime("%a, %d %b %Y %H:%M:%S GMT", t),
            "assets": assets or [], "library": library}


# ---------------------------------------------------------------- Invisible: metadata

def xmp(i: dict) -> str:
    """XMP packet: the metadata format image software reads."""
    return f"""<?xpacket begin="﻿" id="W5M0MpCehiHzreSzNTczkc9d"?>
<x:xmpmeta xmlns:x="adobe:ns:meta/">
 <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">
  <rdf:Description rdf:about=""
    xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/"
    xmlns:xmp="http://ns.adobe.com/xap/1.0/"
    xmlns:xmpMM="http://ns.adobe.com/xap/1.0/mm/"
    Iptc4xmpExt:DigitalSourceType="{SOURCE_TYPE}"
    xmp:CreatorTool="{GENERATOR}"
    xmp:CreateDate="{i['date']}"
    xmpMM:DocumentID="urn:uuid:{i['id']}"/>
 </rdf:RDF>
</x:xmpmeta>
<?xpacket end="r"?>"""


def mark_png(path: Path, i: dict, visible: bool) -> None:
    image = Image.open(path)
    image.load()
    if visible:
        image = banner(image, i["day"])
    # PNG text fields, for simple tools.
    meta = PngInfo()
    meta.add_text("Software", GENERATOR)
    meta.add_text("Creation Time", i["rfc1123"])
    meta.add_text("Source", f"{GENERATOR} (Blender 5.2)")
    meta.add_text("Disclaimer", "Generated by AI")
    if i.get("assets"):  # library assets used (module 5)
        meta.add_text("Assets", ", ".join(f"{a['name']} ({a['source']}, {a['license']})" for a in i["assets"]))
    # The XMP packet, under its standard keyword in a PNG.
    meta.add_itxt("XML:com.adobe.xmp", xmp(i))
    # Saved again by Pillow: Blender's metadata is replaced.
    image.save(path, pnginfo=meta)


# ---------------------------------------------------------------- Visible: the banner

def banner(image: Image.Image, day: str) -> Image.Image:
    """Always identical: same font, same size, same place. Only the date changes."""
    text = f"{GENERATOR} · {day}"
    font = ImageFont.truetype(FONT, 22)
    layer = Image.new("RGBA", image.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    left, top, right, bottom = d.textbbox((0, 0), text, font=font)
    # Bottom right: 16 px margin, 10 and 8 px padding.
    x1, y1 = image.width - 16, image.height - 16
    x0, y0 = x1 - (right - left) - 20, y1 - (bottom - top) - 16
    d.rectangle((x0, y0, x1, y1), fill=(0, 0, 0, 153))  # black at 60 %
    d.text((x0 + 10 - left, y0 + 8 - top), text, font=font, fill="white")
    return Image.alpha_composite(image.convert("RGBA"), layer).convert("RGB")


# ---------------------------------------------------------------- 3D model: the GLB

def mark_glb(path: Path, i: dict) -> None:
    """A GLB: a 12-byte header, then a JSON chunk, where `asset` is rewritten."""
    data = path.read_bytes()
    length, kind = struct.unpack_from("<I4s", data, 12)  # first chunk
    if data[:4] != b"glTF" or kind != b"JSON":
        raise ValueError("unexpected GLB file")
    doc = json.loads(data[20:20 + length])
    asset = doc.setdefault("asset", {})
    asset["extras"] = {
        **asset.get("extras", {}),
        "digitalSourceType": SOURCE_TYPE,
        "createDate": i["date"],
        "id": f"urn:uuid:{i['id']}",
        "exportedBy": asset.get("generator", ""),
    }
    if i.get("assets"):  # the asset trace: name, source, license (module 5)
        asset["extras"]["assets"] = i["assets"]
        asset["extras"]["library"] = i["library"]
    asset["generator"] = GENERATOR
    js = json.dumps(doc, ensure_ascii=False, separators=(",", ":")).encode()
    js += b" " * (-len(js) % 4)       # four-byte alignment
    rest = data[20 + length:]         # binary chunk, unchanged
    total = 20 + len(js) + len(rest)  # lengths recomputed
    path.write_bytes(struct.pack("<4sII", b"glTF", 2, total)
                     + struct.pack("<I4s", len(js), b"JSON") + js + rest)
